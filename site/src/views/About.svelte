<h1>About</h1>
<p>
  Fleetkit asks how many headless Chromium browsers, each in its own microVM, one worker host can run at the same time
  while every shopping task stays inside its latency targets, and what a task costs at that number. It is the design of
  one slice of an agentic browser platform, the compute hosts, worked out by one engineer directing a team of AI agents:
  they built enough of the surrounding system to test the design, ran the experiments as campaigns, and publish the
  results here with <a href="#/method">the method</a> that produced them. The code is at
  <a href="https://github.com/evandbrown/fleetkit" rel="noopener">github.com/evandbrown/fleetkit</a>.
</p>
